// Copies the web app's brand files into the Keycloak sign-in theme, so the theme needs no
// build step of its own: the brand tokens (the `:root` block at the end of
// packages/ui/src/styles.css), the self-hosted Poppins fonts and their licence, the ring of
// stars and the favicons. Run it after changing any of them (`make -C frontend keycloak_theme`)
// and commit the result; packages/ui/src/keycloakTheme.test.ts fails while they differ.
//
// `--check` reports files that are out of date instead of writing them.

import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const frontend = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
export const themeResources = path.resolve(
  frontend,
  "../deploy/helm/ehds-relay/files/keycloak-theme/login/resources",
);
const poppins = path.join(
  frontend,
  "packages/web/node_modules/@fontsource/poppins",
);
const weights = [400, 500, 600, 700];

/** The brand `:root { ... }` block of styles.css, from its leading comment to the closing brace. */
export function brandBlock(styles) {
  const start = styles.indexOf("/* Brand layer");
  const open = styles.indexOf(":root {", start);
  const close = styles.indexOf("\n}", open);
  if (start < 0 || open < 0 || close < 0) {
    throw new Error("no brand :root block in packages/ui/src/styles.css");
  }
  return styles.slice(start, close + 2);
}

const tokensHeader = `/* Generated by frontend/scripts/sync-keycloak-theme.mjs from packages/ui/src/styles.css.
   Do not edit: change the web app's tokens and run \`make -C frontend keycloak_theme\`. */

`;

const fontsCss =
  `/* Generated by frontend/scripts/sync-keycloak-theme.mjs: Poppins from @fontsource/poppins,
   latin subset, served by Keycloak (no font CDN). Licence: ../fonts/OFL.txt. */
` +
  weights
    .map(
      (weight) => `
@font-face {
  font-family: "Poppins";
  font-style: normal;
  font-display: swap;
  font-weight: ${weight};
  src: url("../fonts/poppins-latin-${weight}-normal.woff2") format("woff2");
}
`,
    )
    .join("");

/** Every theme file this script owns: [path inside the theme's resources, contents]. */
export async function expectedFiles() {
  const styles = await readFile(
    path.join(frontend, "packages/ui/src/styles.css"),
    "utf8",
  );
  const files = [
    ["css/tokens.css", tokensHeader + brandBlock(styles) + "\n"],
    ["css/fonts.css", fontsCss],
    ["fonts/OFL.txt", await readFile(path.join(poppins, "LICENSE"))],
  ];
  for (const weight of weights) {
    const name = `poppins-latin-${weight}-normal.woff2`;
    files.push([
      `fonts/${name}`,
      await readFile(path.join(poppins, "files", name)),
    ]);
  }
  for (const name of ["stars.svg", "favicon-32.png", "favicon-64.png"]) {
    files.push([
      `img/${name}`,
      await readFile(path.join(frontend, "packages/web/public", name)),
    ]);
  }
  return files;
}

async function main() {
  const checkOnly = process.argv.includes("--check");
  const stale = [];
  for (const [name, contents] of await expectedFiles()) {
    const target = path.join(themeResources, name);
    const current = await readFile(target).catch(() => null);
    if (current && Buffer.compare(current, Buffer.from(contents)) === 0)
      continue;
    stale.push(name);
    if (!checkOnly) {
      await mkdir(path.dirname(target), { recursive: true });
      await writeFile(target, contents);
    }
  }
  if (checkOnly && stale.length) {
    console.error(
      `Keycloak theme out of date: ${stale.join(", ")}. Run make -C frontend keycloak_theme.`,
    );
    process.exit(1);
  }
  console.log(
    stale.length ? `Updated ${stale.join(", ")}` : "Keycloak theme up to date",
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await main();
}
